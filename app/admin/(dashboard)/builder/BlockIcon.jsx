export default function BlockIcon({ type, icon, size = 18, color = 'currentColor', className, style }) {
    let Component = null;
    if (type && TYPE_MAP[type]) {
        Component = TYPE_MAP[type];
    } else if (icon && EMOJI_MAP[icon]) {
        Component = EMOJI_MAP[icon];
    } else if (type && EMOJI_MAP[type]) {
        Component = EMOJI_MAP[type];
    } else {
        Component = Layers;
    }

    return <Component size={size} color={color} className={className} style={{ display: 'inline-block', verticalAlign: 'middle', flexShrink: 0, ...style }} />;
}
